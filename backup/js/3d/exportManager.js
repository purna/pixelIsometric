'3. For URP: use the **Universal Render Pipeline Asset** and ensure',
'   *Cast Shadows* is enabled on the renderer.',
'',
'## Colliders',
'',
'Box colliders are added by default with sizes matching the exported geometry.',
'Set **Collider Type** to `mesh` in the editor UI for non-box shapes',
