let exportManager = null;

export function initExportManager(scene, objects, layerManager, textureManager) {
    exportManager = new ExportManager(scene, objects, layerManager, textureManager);
    return exportManager;
}

export function getExportManager() {
    return exportManager;
}

export { ExportManager };
